"""
validate_with_tp.py —— 用现成 TwoPunctures (Ansorg+2004, Einstein Toolkit 官方) 交叉验证自研谱求解器
====================================================================================================

原理:
    TwoPunctures 与 paper/tools/spectral_reference.py 解**同一个**哈密顿约束方程
    (Bowen-York puncture, ψ = 1 + Σm/2r + u), 但基函数完全不同
    (TP: 单域紧化 (A,B,φ) 谱 + Newton; 自研: (r,θ,φ) 球谐×逐 l Chebyshev 径向 LU)。
    逐点对比两者 u 即为独立交叉验证。

配置:
    a2_q20   : A2 非等质量 q=2 (m+=0.5@+3, m-=1.0@-3, P=(0,±0.2,0), S=0)
               vs paper/tools/refs_a2/ref_a2_q20.npz
    a3_0164  : A3 train_0164 (非等质量+自旋, 参数从 runs/multi_param_v5/configs.json 读取)
               vs paper/tools/refs/ref_train_0164.npz
    平移不变性处理: TP 强制奇点位于 x'=±par_b; A3 配置 x+≠|x-| 时,
    取 b=(x+-x-)/2, c=(x++x-)/2, 在 TP 坐标 x'=x-c 求解; 对比时把自研解
    在 x=x'+c 处求值 (椭圆方程与 BY 源均平移不变, 严格等价)。

运行前提:
    - WSL Ubuntu-24.04 已装 libgsl-dev, TwoPuncturesC 已 make, dump_psi_grid 已编译
      (编译命令见 paper/tools/solver_cross_validation.md)
    - 本机 venv 有 torch/numpy (评估自研解)

用法:
    .venv/Scripts/python.exe -u paper/tools/validate_with_tp.py            # 全部
    ... --labels a2_q20 --npoints 60 96                                    # 选择
输出:
    paper/tools/tp_work/<label>_n<np>.par / .psi
    paper/tools/tp_work/tp_vs_ours.json (逐配置指标) + 控制台汇总
"""

import argparse, json, os, re, subprocess, sys, time
import numpy as np
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                       # paper/
WSL_TP = "/mnt/d/AIs/PINN/TwoPuncturesC"
WSL_WORK = "/mnt/d/AIs/PINN/paper/tools/tp_work"
WIN_WORK = os.path.join(HERE, "tp_work")
WSL = ["wsl", "-d", "Ubuntu-24.04", "--"]

# a3_0164 的参数在运行时从 configs.json 读取, 避免硬编码
def load_a3_raw(label="train_0164"):
    cfg = json.load(open(os.path.join(ROOT, "runs", "multi_param_v5", "configs.json")))
    for e in cfg["train"]:
        if e["label"] == label:
            # 必须转成 python float: np.float64 的 repr 是 "np.float64(...)",
            # 写进 par 文件后 TP 解析不出(静默变成 0 → NaN → 断言崩溃)
            return [float(v) for v in np.array(e["raw"], dtype=float)]
    raise KeyError(label)

def a2_q20():
    return dict(m=[0.5, 1.0], xs=[[3.0, 0, 0], [-3.0, 0, 0]],
                Ps=[[0, 0.2, 0], [0, -0.2, 0]], Ss=[[0, 0, 0], [0, 0, 0]],
                ref=os.path.join(ROOT, "tools", "refs_a2", "ref_a2_q20.npz"))

def a3_0164():
    raw = load_a3_raw("train_0164")
    m = [float(raw[0]), float(raw[1])]
    xs = [[float(raw[2]), 0, 0], [float(raw[3]), 0, 0]]
    Ps = [[0, float(raw[4]), 0], [0, float(raw[5]), 0]]
    Ss = [[0, 0, float(raw[6])], [0, 0, float(raw[7])]]
    return dict(m=m, xs=xs, Ps=Ps, Ss=Ss,
                ref=os.path.join(ROOT, "tools", "refs", "ref_train_0164.npz"))

CONFIGS = {"a2_q20": a2_q20, "a3_0164": a3_0164}


def centered(cfg):
    """返回 (b, c): TP 在 x'=x-c 中求解, 奇点位于 x'=±b。"""
    xp, xm = cfg["xs"][0][0], cfg["xs"][1][0]
    return (xp - xm) / 2.0, (xp + xm) / 2.0


