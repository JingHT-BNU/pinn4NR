def blocks_args(b):
    """四个网格块: 两个奇点邻域(±b±1.5, 121³, 步长0.025) + x 轴薄板(321×5×5, 含轴上精确行) + 外层(±31, 61³)。"""
    a = []
    for s in (+1.0, -1.0):
        a += [f"{s*b-1.5:.6f}", f"{s*b+1.5:.6f}", "-1.5", "1.5", "-1.5", "1.5",
              "121", "121", "121"]
    a += [f"{-(b+8):.6f}", f"{b+8:.6f}", "-0.06", "0.06", "-0.06", "0.06",
          "321", "5", "5"]
    a += ["-31", "31", "-31", "31", "-31", "31", "61", "61", "61"]
    return a


def run_tp(label, npoints, b):
    par_win = os.path.join(WIN_WORK, f"{label}_n{npoints}.par")
    psi_win = os.path.join(WIN_WORK, f"{label}_n{npoints}.psi")
    write_par_from_cfg(label, b, npoints, par_win)
    # WSL 路径必须用正斜杠手工拼接(os.path.join 在 Windows 会插入反斜杠,
    # 传进 Linux 后成为文件名字符 → 静默打开失败)
    par_wsl = f"{WSL_WORK}/{label}_n{npoints}.par"
    psi_wsl = f"{WSL_WORK}/{label}_n{npoints}.psi"
    exe_wsl = f"{WSL_WORK}/dump_psi_grid"
    cmd = WSL + [exe_wsl, "--adaptive", par_wsl, f"{b:.6f}", psi_wsl] + blocks_args(b)
    t0 = time.time()
    r = subprocess.run(cmd, capture_output=True, text=True)
    log = r.stdout + r.stderr
    adm = re.findall(r"ADM [Mm]ass[^\n]*", log)
    print(f"[TP] {label} n={npoints}: rc={r.returncode}, {time.time()-t0:.0f}s"
          + (f"; {adm}" if adm else ""), flush=True)
    if r.returncode != 0 or not os.path.exists(psi_win):
        print(log[-3000:], flush=True)
        raise RuntimeError(f"TP run failed or no output: {label} n={npoints}")
    with open(os.path.join(WIN_WORK, f"{label}_n{npoints}.log"), "w", encoding="utf-8", errors="replace") as f:
        f.write(log)
    return psi_win, adm


def write_par_from_cfg(label, b, npoints, path):
    cfg = CONFIGS[label]()
    write_par(cfg, b, npoints, path)


def load_psi(path):
    try:
        import pandas as pd
        df = pd.read_csv(path, sep=r"\s+", header=None, names=["x", "y", "z", "psi"])
        return df.to_numpy()
    except ImportError:
        return np.loadtxt(path)


def compare(label, npoints, b, c, device):
    cfg = CONFIGS[label]()
    m1, m2 = cfg["m"]
    x1, x2 = cfg["xs"][0], cfg["xs"][1]
    arr = load_psi(os.path.join(WIN_WORK, f"{label}_n{npoints}.psi"))
    # 完整性: 以 TP 日志自报的 "Total written" 为准(块间重叠会被去重),
    # 防止中止/截断的 psi 被静默对比
    log_path = os.path.join(WIN_WORK, f"{label}_n{npoints}.live.log")
    m = re.search(r"Total written: (\d+) grid points", open(log_path, encoding="utf-8", errors="replace").read())
    if not m:
        raise RuntimeError(f"{label} n={npoints}: live.log 无 'Total written'(求解未完成?)")
    expected = int(m.group(1))
    if arr.shape[0] != expected:
        raise RuntimeError(f"{label} n={npoints}: psi 点数 {arr.shape[0]} != 日志报告 {expected}"
                           "(求解被中止或截断?)")
    xp_tp, yp_tp, zp_tp, psi = arr[:, 0], arr[:, 1], arr[:, 2], arr[:, 3]
    # TP 坐标 x' → 我们的坐标 x = x' + c
    x_o = xp_tp + c
    pts = np.stack([x_o, yp_tp, zp_tp], axis=1)
    r1 = np.linalg.norm(pts - np.array(x1), axis=1)
    r2 = np.linalg.norm(pts - np.array(x2), axis=1)
    rmin = np.minimum(r1, r2)
    keep = rmin > 0.05
    psi, pts, rmin, r1, r2 = psi[keep], pts[keep], rmin[keep], r1[keep], r2[keep]
    u_tp = psi - 1.0 - m1 / (2 * r1) - m2 / (2 * r2)

    from spectral_reference import SpectralPunctureSolver
    ev = SpectralPunctureSolver.from_coefficients(cfg["ref"], device=device, verify=False)
    u_ours = ev.evaluate(pts, chunk=16384, dtype=torch.float64).astype(float)

    d = u_ours - u_tp
    def l2re(mask=None):
        if mask is None:
            num, den = d, u_tp
        else:
            num, den = d[mask], u_tp[mask]
        return float(np.sqrt(np.sum(num**2) / max(np.sum(den**2), 1e-300)))
    reg = {
        "r<0.5": rmin < 0.5, "0.5-2": (rmin >= 0.5) & (rmin < 2),
        "2-10": (rmin >= 2) & (rmin < 10), ">10": rmin >= 10,
        "axis(y=z=0)": (np.abs(pts[:, 1]) < 1e-9) & (np.abs(pts[:, 2]) < 1e-9),
    }
    out = {
        "n_points": int(len(d)), "L2RE_all": l2re(),
        "regions": {k: l2re(m) for k, m in reg.items() if m.any()},
        "max_abs_diff": float(np.max(np.abs(d))),
        "median_abs_diff": float(np.median(np.abs(d))),
    }
    print(f"[CMP] {label} n={npoints}: L2RE_all={out['L2RE_all']:.3e}  "
          + "  ".join(f"{k}={v:.3e}" for k, v in out["regions"].items()), flush=True)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--labels", default="a2_q20,a3_0164")
    ap.add_argument("--npoints", type=int, nargs="+", default=[60, 96])
    args = ap.parse_args()
    device = "cuda" if torch.cuda.is_available() else "cpu"
    os.makedirs(WIN_WORK, exist_ok=True)
    report = {}
    for label in args.labels.split(","):
        cfg = CONFIGS[label]()
        b, c = centered(cfg)
        per = {}
        for np_ in args.npoints:
            run_tp(label, np_, b)
            per[f"n{np_}"] = compare(label, np_, b, c, device)
        if len(args.npoints) > 1:
            n1, n2 = [f"n{n_}" for n_ in args.npoints[:2]]
            per["tp_selfconv_L2RE"] = "见 tp_vs_ours.json (n60 vs n96 同网格逐点)"
        report[label] = per
        json.dump(report, open(os.path.join(WIN_WORK, "tp_vs_ours.json"), "w"), indent=2)
    print("DONE ->", os.path.join(WIN_WORK, "tp_vs_ours.json"), flush=True)


if __name__ == "__main__":
    main()
